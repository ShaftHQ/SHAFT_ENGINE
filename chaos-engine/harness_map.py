#!/usr/bin/env python3
"""Generate and check the lazy harness map (#7242): one line per harness file.

Entry prints one pointer line; bodies load on demand. Zero LLM, stdlib only.

    python3 .chaos-engine/harness_map.py --check
    python3 chaos-engine/harness_map.py --write   # repo-only: source tree
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAP = "references/harness-map.md"
WIDTH = 90
SCOPES = (
    ("Core", ("identity.md",)),
    ("Companions", ("companions/*.md",)),
    ("Skills", ("skills/*/SKILL.md",)),
    ("References", ("references/*.md",)),
    ("Hooks", ("hooks/*.py",)),
    ("Tools", ("*.py",)),
)


def mapped_files(root: Path = HERE) -> list[tuple[str, str]]:
    seen: set[str] = set()
    rows = []
    for group, patterns in SCOPES:
        for pattern in patterns:
            for path in sorted(root.glob(pattern)):
                relative = path.relative_to(root).as_posix()
                if relative in seen or relative == MAP or not path.is_file():
                    continue
                seen.add(relative)
                rows.append((group, relative))
    return rows


def summary(path: Path) -> str:
    text = path.read_text(encoding="utf-8", errors="replace")
    if path.suffix == ".py":
        try:
            doc = ast.get_docstring(ast.parse(text)) or ""
        except SyntaxError:
            doc = ""
        line = doc.strip().splitlines()[0] if doc.strip() else ""
    else:
        match = re.search(r"^description:\s*>?-?\s*\n?((?:\s+.+\n?)+|.+)", text, re.M)
        if text.startswith("---") and match:
            line = " ".join(match.group(1).split())
        else:
            heading = re.search(r"^#\s+(.+)$", text, re.M)
            line = heading.group(1).strip() if heading else ""
    line = re.sub(r"\s*\(?#\d{3,5}\)?:?", "", line)
    line = line.replace("|", "/").strip() or "(no summary; open to read)"
    return line if len(line) <= WIDTH else line[: WIDTH - 1].rstrip() + "…"


def render(root: Path = HERE) -> str:
    rows = mapped_files(root)
    out = [
        "# Harness map",
        "",
        "Generated by [harness_map.py](../harness_map.py); run "
        "`python3 .chaos-engine/harness_map.py --check`. One line per harness file; "
        "open a body only when its line matches the task. Skills: [catalog](catalog.md).",
        "",
    ]
    group = None
    for name, relative in rows:
        if name != group:
            out += ["", f"## {name}", ""] if group else [f"## {name}", ""]
            group = name
        out.append(f"- `{relative}`: {summary(root / relative)}")
    return "\n".join(out) + "\n"


def entry_line(root: Path = HERE) -> str:
    return f"index: {len(mapped_files(root))} files, `.chaos-engine/{MAP}`\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--check", action="store_true")
    action.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    target = HERE / MAP
    rendered = render()
    if args.write:
        target.write_text(rendered, encoding="utf-8")
        return 0
    current = target.read_text(encoding="utf-8") if target.is_file() else ""
    if current != rendered:
        print(f"{MAP} is stale: run python3 chaos-engine/harness_map.py --write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
