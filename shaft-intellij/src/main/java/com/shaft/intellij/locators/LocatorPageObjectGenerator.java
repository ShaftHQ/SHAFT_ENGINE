package com.shaft.intellij.locators;

import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Turns ranked locator inspector rows into a simple page-object Java snippet (W2.11 / #7595).
 */
public final class LocatorPageObjectGenerator {
    public record LocatorRow(
            @NotNull String name,
            @NotNull String shaftExpression,
            boolean hittable,
            boolean visible,
            boolean enabled,
            int recommendationRank
    ) {
    }

    private LocatorPageObjectGenerator() {
        throw new IllegalStateException("Utility class");
    }

    public static @NotNull String generate(@NotNull String className, @NotNull List<LocatorRow> rows) {
        String safeClass = sanitizeTypeName(className);
        StringBuilder sb = new StringBuilder();
        sb.append("package pages;\n\n");
        sb.append("import com.shaft.driver.SHAFT;\n\n");
        sb.append("/** Generated by SHAFT locator inspector — review before committing. */\n");
        sb.append("public class ").append(safeClass).append(" {\n");
        sb.append("    private final SHAFT.GUI.WebDriver driver;\n\n");
        sb.append("    public ").append(safeClass).append("(SHAFT.GUI.WebDriver driver) {\n");
        sb.append("        this.driver = driver;\n");
        sb.append("    }\n");
        List<LocatorRow> ordered = new ArrayList<>(rows);
        ordered.sort((a, b) -> Integer.compare(a.recommendationRank(), b.recommendationRank()));
        for (LocatorRow row : ordered) {
            if (!row.hittable() || !row.visible() || !row.enabled()) {
                sb.append("\n    // WARNING: element '").append(row.name())
                        .append("' flagged non-hittable/visible/enabled — verify before use.\n");
            }
            sb.append("\n    public SHAFT.GUI.Locator ").append(sanitizeMethodName(row.name())).append("() {\n");
            sb.append("        return ").append(row.shaftExpression().trim()).append(";\n");
            sb.append("    }\n");
        }
        sb.append("}\n");
        return sb.toString();
    }

    public static @NotNull String crossPlatformPairFields(
            @NotNull String androidExpression,
            @NotNull String iosExpression
    ) {
        return "android=" + androidExpression.trim() + "\nios=" + iosExpression.trim() + "\n";
    }

    private static String sanitizeTypeName(@Nullable String name) {
        String raw = name == null || name.isBlank() ? "GeneratedPage" : name.trim();
        String cleaned = raw.replaceAll("[^A-Za-z0-9_]", "");
        if (cleaned.isEmpty()) {
            return "GeneratedPage";
        }
        return Character.toUpperCase(cleaned.charAt(0)) + cleaned.substring(1);
    }

    private static String sanitizeMethodName(String name) {
        String cleaned = name.replaceAll("[^A-Za-z0-9_]", "");
        if (cleaned.isEmpty()) {
            return "element";
        }
        String withPrefix = cleaned.substring(0, 1).toLowerCase(Locale.ROOT) + cleaned.substring(1);
        if (!Character.isLetter(withPrefix.charAt(0))) {
            return "element" + withPrefix;
        }
        return withPrefix;
    }
}
